        ImageVector.Builder(name, 48.dp, 48.dp, 48f, 48f).apply {
            paths.forEach { d ->
                addPath(
                    addPathNodes(d), fill = if (filled) SolidColor(Color.Black) else null, stroke = SolidColor(Color.Black), strokeLineWidth = strokeWidth,
